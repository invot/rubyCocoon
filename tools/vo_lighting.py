def summarize(path):
    path = Path(path)
    data = json.loads(path.read_text(encoding="utf-8"))
    if data["problems"] or data["focus_losses"] or len(data["passes"]) != 3:
        raise ValueError("Incomplete or interrupted lighting experiment")
    batches = data["passes"]
    scenes = set(batches[0]["segments"])
    if scenes not in [{"hero_house", "largest_interior"}, {"hero_house", "largest_interior", "hatch", "merge"}]:
        raise ValueError("Missing lighting scenes")
    settings = ["render_height", "render_size", "refresh_hz", "vsync", "max_fps", "quality"]
    for index, batch in enumerate(batches):
        if batch["focus_losses"] or set(batch["segments"]) != scenes:
            raise ValueError("Route/focus changed")
        if any(batch[key] != batches[0][key] for key in settings):
            raise ValueError("Settings changed during lighting experiment")
        for name, segment in batch["segments"].items():
            validate_segment(segment)
            experiment = segment["experiment"]
            if name in ["hero_house", "largest_interior"]:
                if segment["frames"] != 240 or experiment["distance"] != [100, 30, 100][index] or experiment["splits"] != [2, 1, 2][index]:
                    raise ValueError("Indoor controls did not take effect")
                if experiment["map"] != batches[0]["segments"][name]["experiment"]["map"]:
                    raise ValueError("Indoor map changed")
            else:
                if segment["frames"] != (504 if name == "hatch" else 570) or experiment["key_shadow"] != (index != 1):
                    raise ValueError("Film controls did not take effect")
                if abs(experiment["elapsed"] - segment["frames"] / 60) > .00001:
                    raise ValueError("Film timeline did not advance at the recorded fixed dt")
                expected_range = 26 if name == "hatch" else 41.6
                if abs(experiment["key_range"] - expected_range) > .001:
                    raise ValueError("Hatch/merge stage range changed")
                for key in ["key_range", "key_angle", "stage_scale", "simulation_dt", "viewport_size"]:
                    if experiment[key] != batches[0]["segments"][name]["experiment"][key]:
                        raise ValueError("Film setup changed")
    result = {"platform": data["platform"], "renderer": data["renderer"],
              "settings": {k: batches[0][k] for k in settings}, "window": data["window"], "scenes": {}}
    lines = ["<!-- Generated by tools/vo_lighting.py -->", "",
             f"{data['platform']} / {data['renderer']}; indoor old/approved/old, film key-shadow on/off/on.", "",
             f"Reported refresh {batches[0]['refresh_hz']} Hz, cap {batches[0]['max_fps']}, quality {batches[0]['quality']}, render size {batches[0]['render_size']}.", "",
             "GPU medians are viewport measurements. Frame intervals include pacing; net changes are not isolated GPU-pass timestamps.",
             "Film timelines advance at fixed 1/60 s; shader time and particles follow render time. Peak is the largest sampled viewport GPU counter, not a frame-exact hardware trace.", "",
             "| Scene | GPU median ms A/B/A | Mean A minus B | A GPU drift | GPU p95 A/B/A | GPU max A/B/A | Frame medians A/B/A |",
             "|---|---|---:|---:|---|---|---|"]
    for scene in sorted(scenes):
        segments = [p["segments"][scene] for p in batches]
        medians = [s["summary"]["gpu_ms"]["median"] for s in segments]
        available = min(medians) > 0 and all(s["availability"]["gpu_timing"] for s in segments)
        delta = (medians[0] + medians[2])/2 - medians[1] if available else None
        drift = (medians[2]/medians[0]-1)*100 if available else None
        result["scenes"][scene] = {"gpu_delta_ms": delta, "gpu_drift_percent": drift,
                                   "experiments": [s["experiment"] for s in segments],
                                   "summaries": [s["summary"] for s in segments]}
        if scene in ["hatch", "merge"]:
            result["scenes"][scene]["largest_gpu_samples"] = [[
                {"frame": i, "simulation_s": i/60, "gpu_ms": segment["trace"]["gpu_ms"][i]}
                for i in sorted(range(segment["frames"]), key=lambda j: segment["trace"]["gpu_ms"][j], reverse=True)[:5]]
                for segment in segments]
        columns = ["/".join(f"{s['summary']['gpu_ms'][metric]:.3f}" for s in segments) for metric in ["median", "p95", "max"]]
        frames = "/".join(f"{s['summary']['frame_ms']['median']:.2f}" for s in segments)
        lines.append(f"| {scene} | {columns[0]} | " + (f"{delta:.3f} | {drift:+.1f}%" if available else "unavailable | unavailable") +
                     f" | {columns[1]} | {columns[2]} | {frames} |")
    if data["platform"] == "Android":
        folder = path.parent
        if data["renderer"] != "mobile" or not data["touch_controls_visible"] or not data["screen_keep_on"]:
            raise ValueError("Unexpected phone renderer/controls")
        if (folder / "player-package-before.txt").read_bytes() != (folder / "player-package-after.txt").read_bytes():
            raise ValueError("Player package changed")
        temperatures = json.loads((folder / "temperatures.json").read_text(encoding="utf-8"))
        values = [t["temperature_c"] for t in temperatures if t["temperature_c"] is not None]
        result["temperatures"] = {"min_c": min(values), "max_c": max(values), "largest_gap_s": max(
            (b["elapsed_s"]-a["elapsed_s"] for a,b in zip(temperatures, temperatures[1:])), default=0)}
    path.with_name("validated-lighting.json").write_text(json.dumps(result, indent=2)+"\n", encoding="utf-8")
    path.with_name("lighting.md").write_text("\n".join(lines)+"\n", encoding="utf-8")
    print("\n".join(lines))
    return result


def configure_phone():
    sweep.configure("008b")
    phone.RUN_METADATA = {"experiment": "indoor old/approved/old; film OculusKey on/off/on", "quality": "mid", "passes_target": 3}
    phone.EXTRA_ARGS = phone.EXTRA_ARGS.replace("--scene=vo-perf", "--scene=vo-lighting").replace("--resolution_sweep=720,540,720 ", "")


def desktop(args):
    if not args.attempt or any(c not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-" for c in args.attempt):
        raise ValueError("Use a new plain --attempt name")
    folder = ROOT / "build/perf/vo/008b" / args.attempt
    folder.mkdir(parents=True, exist_ok=False)
    state = f"res://build/vo_state/008b/{args.attempt}"
    report = folder / "report.json"
    command = [args.godot, "--path", str(ROOT), "--rendering-method", args.renderer, "--resolution", "2400x1080" if args.touch else "1920x1080", "--",
               "--scene=vo-lighting", "--graphics_quality=mid", "--render_height=720", "--duration=0",
               f"--report={report.as_posix()}", f"--shots=res://build/shots/vo/008b/{args.attempt}", "--shot_w=0",
               f"--save_dir={state}/saves/", f"--prefs_path={state}/settings.cfg"]
    if args.touch:
        command.append("--touch")
    (folder / "command.json").write_text(json.dumps(command, indent=2), encoding="utf-8")
    with model_lock(timeout=3600), (folder / "run.log").open("w", encoding="utf-8") as log:
        print("Running lighting experiment; keep the game focused", flush=True)
        completed = subprocess.run(command, cwd=ROOT, stdout=log, stderr=subprocess.STDOUT, timeout=900)
    text = (folder / "run.log").read_text(encoding="utf-8")
    runtime_errors = [line for line in text.splitlines() if "SCRIPT ERROR" in line or "Failed loading resource" in line or
                      ("ERROR:" in line and "resources still in use at exit" not in line)]
    if completed.returncode or runtime_errors or "VO PERF DONE: 0 problem(s)" not in text:
        (folder / "INVALID.txt").write_text("Not accepted measurement evidence; inspect run.log\n", encoding="utf-8")
        raise RuntimeError("Lighting run failed: " + str(folder))
    if json.loads(report.read_text(encoding="utf-8"))["renderer"] != args.renderer:
        raise ValueError("Renderer fallback")
    summarize(report)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["desktop", "export", "phone", "summary"])
    parser.add_argument("report", nargs="?")
    parser.add_argument("--attempt", default="")
    parser.add_argument("--renderer", choices=["mobile", "forward_plus", "gl_compatibility"], default="mobile")
    parser.add_argument("--touch", action="store_true")
    parser.add_argument("--godot", default=os.environ.get("GODOT", "C:/Program Files/Godot/Godot_v4.7-stable_win64.exe"))
    parser.add_argument("--sdk", default=str(ROOT / "build/tools/android"))
    parser.add_argument("--java", default=os.environ.get("JAVA_HOME", "C:/Program Files/Eclipse Adoptium/jdk-17.0.20.101-hotspot"))
    parser.add_argument("--serial", default="ZY22K7BD2J")
    parser.add_argument("--display", default="")
    parser.add_argument("--attach", action="store_true")
    args = parser.parse_args()
    if args.action == "summary":
        if not args.report:
            parser.error("summary requires a report path")
        summarize(args.report)
    elif args.action == "desktop":
        desktop(args)
    else:
        configure_phone()
        if args.action == "export":
            with model_lock(timeout=3600):
                phone.export(args)
        else:
            sweep.run(args)
            summarize(phone.OUT / "report.json")
