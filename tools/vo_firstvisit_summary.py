"""Validate and compare the focused step 009b loading-only experiments."""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "build/perf/vo/009b"


def main(tags):
    output = {}
    rows = ["<!-- Generated by python tools/vo_firstvisit_summary.py -->", "",
            "| Experiment | Cache enabled | Shared warm-up | Pass | Map | Continuous black ms | Legacy sampled ms | Warm-up draws |",
            "|---|---|---|---:|---|---:|---:|---:|"]
    for tag in tags:
        data = json.loads((BASE / tag / "gl_compatibility-cost.json").read_text())
        assert data["loading_only"] and data["renderer"] == "gl_compatibility"
        assert not data["problems"] and not data["focus_losses"] and len(data["passes"]) == 2
        result = []
        for index, batch in enumerate(data["passes"]):
            assert not batch["focus_losses"] and not batch["segments"]
            assert [t["map"] for t in batch["transitions"]] == ["route1", "caccoon", "caccoon#1", "tidewater"]
            for transition in batch["transitions"]:
                continuous = transition["continuous_black_ms"]
                phases = transition["loading_phases_ms"]
                assert len(phases) == 12 and all(math.isfinite(v) and v >= 0 for v in phases.values())
                assert abs(continuous-sum(phases.values())) < 2
                assert continuous <= transition["total_ms"]
                result.append({"pass": index+1, **transition})
                warm = transition.get("warmup") or {}
                rows.append(f"| {tag} | {data['shader_cache_enabled']} | {bool(data.get('warmup_shared'))} | {index+1} | "
                            f"{transition['map']} | {continuous:.1f} | {transition['black_ms']:.1f} | {warm.get('representatives', '')} |")
        output[tag] = {"shader_cache_enabled": data["shader_cache_enabled"], "warmup_shared": bool(data.get("warmup_shared")),
                       "transitions": result}
    (BASE / "validated-first-visits.json").write_text(json.dumps(output, indent=2) + "\n", encoding="utf-8")
    (BASE / "first-visits.md").write_text("\n".join(rows) + "\n", encoding="utf-8")
    print("\n".join(rows))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tags", nargs="+", default=["before-load", "cache-off"])
    main(parser.parse_args().tags)
