"""Generate step 004 numerical tables from raw evidence; no hand-entered ledger counts."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "build/perf/vo/004"


def read(path):
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def main():
    lines = ["<!-- Generated by python tools/vo_cost_summary.py -->", "",
             "### Desktop diagnostic inventory", "",
             "Frustum/AABB end views, including occluded geometry and LOD alternatives. Mesh/MM columns",
             "are **surface submissions by node type**, not actual renderer draw calls. Lights are visible",
             "subtree totals, not lights proven to affect pixels. Alpha includes source-level custom ALPHA mentions.", "",
             "| Renderer | Scene | Mesh / MM surfaces | Materials | Finished surfaces / materials | Shadow nodes | Lights / shadow lights | Blend / custom alpha / cutout |",
             "|---|---|---:|---:|---:|---:|---:|---:|"]
    summary = {"diagnostics": {}, "baseline_targets": {}, "hashes": {}}
    for renderer in ["mobile", "forward_plus", "gl_compatibility"]:
        path = f"build/perf/vo/004/{renderer}-cost.json"
        data = read(path)
        assert not data["problems"] and not data["focus_losses"]
        rows = {}
        for scene, segment in data["segments"].items():
            inv = segment["diagnosis"]["end_view"]
            assert inv["distinct_finished_materials"] <= inv["distinct_materials"]
            assert sum(inv["node_types"].values()) == inv["surfaces"]
            modes = inv["material_modes"]
            types = inv["node_types"]
            rows[scene] = inv
            lines.append(f"| {renderer} | {scene} | {types.get('MeshInstance3D', 0)} / {types.get('MultiMeshInstance3D', 0)} | {inv['distinct_materials']} | {inv['finished_surfaces']} / {inv['distinct_finished_materials']} | {inv['shadow_nodes']} | {inv['lights']} / {inv['shadow_lights']} | {modes.get('alpha_blend', 0)} / {modes.get('custom_alpha', 0)} / {modes.get('alpha_scissor', 0) + modes.get('custom_cutout', 0)} |")
        summary["diagnostics"][renderer] = {"end_views": rows, "transitions": data["transitions"],
            "script_probes": {k: v["diagnosis"].get("script_probes", {}) for k, v in data["segments"].items()}}
    lines += ["", "### Accepted baseline target comparison", "",
              "Values are median frame interval / world-or-battle tick CPU / viewport GPU ms / draw calls.",
              "CPU and GPU counters overlap; do not add them. These are the accepted 001–003 results, not new device runs.", "",
              "| Target | Scene | Frame ms | Tick CPU ms | GPU ms | Draw calls |", "|---|---|---:|---:|---:|---:|"]
    targets = {"desktop-forward": "baseline-desktop/forward.json", "desktop-mobile": "baseline-desktop/mobile.json",
               "desktop-compat": "baseline-desktop/compat.json", "phone": "baseline-phone/report.json", "web": "baseline-web/report.json"}
    for target, filename in targets.items():
        data = read("build/perf/vo/" + filename)
        summary["baseline_targets"][target] = {}
        for scene, seg in data["segments"].items():
            row = {k: seg["summary"][k]["median"] for k in ["frame_ms", "tick_cpu_ms", "gpu_ms", "draw_calls"]}
            summary["baseline_targets"][target][scene] = row
            lines.append(f"| {target} | {scene} | {row['frame_ms']:.3f} | {row['tick_cpu_ms']:.3f} | {row['gpu_ms']:.3f} | {row['draw_calls']:g} |")
    build = read("build/perf/vo/004/build-profile-verified.json")
    lines += ["", "### Headless build phases", "", "CPU-only manual construction harness; excludes production first draw, shader warm-up, audio and battle prewarm.",
              "Totals exclude the separately timed final finish traversal. Deferred automatic finishing can occur within earlier phases.", "",
              "| Map | Total ms | Three largest construction phases (ms) | Final finish traversal ms |", "|---|---:|---|---:|"]
    phases = ["map data", "room", "environment", "terrain", "house plans", "scatter", "backdrop", "buildings list", "street props", "obstacles, boats", "npcs", "items, player", "spawn, wilds", "all buildings"]
    for scene, data in build.items():
        ranked = sorted(((k, data[k]) for k in phases if k in data), key=lambda kv: kv[1], reverse=True)
        lines.append(f"| {scene} | {data['total']:.1f} | " + "; ".join(f"{k}: {v:g}" for k, v in ranked[:3]) + f" | {data['finish pass ms']:.3f} |")
    summary["build_profile"] = build
    for path in sorted(OUT.glob("*.json")):
        if path.name != "summary.json":
            summary["hashes"][path.name] = hashlib.sha256(path.read_bytes()).hexdigest()
    (OUT / "summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    (OUT / "tables.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Validated and generated", OUT / "tables.md")


if __name__ == "__main__":
    main()
