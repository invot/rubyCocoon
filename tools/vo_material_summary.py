"""Generate the 005a material-eligibility table from the conservative property audit."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "build/perf/vo/004/material-eligibility.json"
OUT = ROOT / "build/perf/vo/005a"


if __name__ == "__main__":
    data = json.loads(SOURCE.read_text())
    assert not data["problems"] and not data["focus_losses"]
    result = {}
    rows = ["<!-- Generated by python tools/vo_material_summary.py -->", "",
            "| Whole subtree | Finished materials | Exact property groups | Redundant resource ceiling |",
            "|---|---:|---:|---:|"]
    for scene, segment in data["segments"].items():
        audit = segment["diagnosis"]["material_eligibility"]
        assert audit["distinct_finished_materials"] - audit["exact_property_groups"] == audit["redundant_resources_upper_bound"]
        result[scene] = audit
        rows.append(f"| {scene} | {audit['distinct_finished_materials']} | {audit['exact_property_groups']} | {audit['redundant_resources_upper_bound']} |")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "eligibility.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    (OUT / "table.md").write_text("\n".join(rows) + "\n", encoding="utf-8")
    print("\n".join(rows))
