"""Validate first/return loading-phase evidence and generate step 009a tables."""
import argparse
import json
import math
from pathlib import Path
from vo_perf import validate

ROOT = Path(__file__).resolve().parents[1]


def main(attempt):
    folder = ROOT / "build/perf/vo/009a" / attempt
    output = {"attempt": attempt, "renderers": {}}
    rows = ["<!-- Generated by python tools/vo_load_summary.py -->", "",
            "| Renderer | Pass | Map | Black ms | Construction ms | Arrival setup ms | First / second frame await ms | Other loading phases ms |",
            "|---|---:|---|---:|---:|---:|---:|---:|"]
    for renderer, config in [("mobile", "mobile"), ("gl_compatibility", "compat")]:
        data = json.loads((folder / f"{renderer}-cost.json").read_text())
        validate(data, config)
        assert not data["focus_losses"] and len(data["passes"]) == 2
        extracted = []
        for index, batch in enumerate(data["passes"]):
            assert not batch["focus_losses"] and len(batch["transitions"]) == 4
            if index:
                for scene, segment in batch["segments"].items():
                    first = data["passes"][0]["segments"][scene]
                    assert segment["frames"] == first["frames"] and segment.get("tiles") == first.get("tiles")
            for transition in batch["transitions"]:
                phases = transition["loading_phases_ms"]
                assert len(phases) == 11 and all(math.isfinite(v) and v >= 0 for v in phases.values())
                total = sum(phases.values())
                assert total <= transition["total_ms"] + 2, (renderer, transition, total)
                first = phases["first process-frame await after enabling viewport"]
                second = phases["second process-frame await"]
                construction = phases["world build"]
                arrival = phases["arrival preparation and warmup setup"]
                other = total - first - second - construction - arrival
                row = {"pass": index + 1, **transition, "phases_sum_ms": total,
                       "phase_ranking": sorted(phases, key=phases.get, reverse=True)}
                extracted.append(row)
                rows.append(f"| {renderer} | {index+1} | {transition['map']} | {transition['black_ms']:.1f} | {construction:.1f} | {arrival:.1f} | {first:.1f} / {second:.1f} | {other:.1f} |")
        output["renderers"][renderer] = extracted
    (folder / "validated-phases.json").write_text(json.dumps(output, indent=2) + "\n", encoding="utf-8")
    (folder / "phases.md").write_text("\n".join(rows) + "\n", encoding="utf-8")
    print("\n".join(rows))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--attempt", default="focused-01")
    main(parser.parse_args().attempt)
