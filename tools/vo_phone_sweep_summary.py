"""Validate the actual-phone resolution sweep and generate step 010a comparison tables."""
import json
import math
from pathlib import Path
import statistics

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "build/perf/vo/010a/phone"


def main():
    data = json.loads((OUT / "report.json").read_text())
    assert data["platform"] == "Android" and data["renderer"] == "mobile"
    assert not data["problems"] and not data["focus_losses"] and data["touch_controls_visible"]
    assert data["screen_keep_on"] and data["input_mode"] == "screen"
    batches = data["passes"]
    assert len(batches) == 3 and [p["render_height"] for p in batches] == [720, 540, 720]
    expected = {"coastal_path", "cove_plaza", "hero_house", "rue_royale", "coast_battle"}
    for batch in batches:
        assert batch["quality"] == "mid" and batch["max_fps"] == 60 and not batch["focus_losses"]
        assert set(batch["segments"]) == expected
        assert batch["render_size"][1] == batch["render_height"]
        assert abs(batch["render_size"][0] - data["window"][0] * batch["render_height"] / data["window"][1]) <= .51
        for scene, segment in batch["segments"].items():
            first = batches[0]["segments"][scene]
            assert segment["frames"] == first["frames"] and segment.get("tiles") == first.get("tiles")
            for metric, trace in segment["trace"].items():
                assert len(trace) == segment["frames"] and all(math.isfinite(v) for v in trace)
                ordered = sorted(trace)
                values = {"median": statistics.median(ordered), "p95": ordered[math.ceil(len(trace)*.95)-1],
                          "p99": ordered[math.ceil(len(trace)*.99)-1], "max": ordered[-1]}
                assert all(math.isclose(segment["summary"][metric][k], v, rel_tol=1e-9, abs_tol=1e-9) for k,v in values.items())
    rows = ["<!-- Generated by python tools/vo_phone_sweep_summary.py -->", "",
            "Frame/GPU columns are medians in ms; 540 GPU reduction compares with the mean of bracketed 720 medians.", "",
            "| Scene | 720 first frame / GPU | 540 frame / GPU | 720 return frame / GPU | GPU reduction at 540 | 720 GPU drift |",
            "|---|---:|---:|---:|---:|---:|"]
    result = {"device": {k:data[k] for k in ["platform", "gpu", "renderer", "window", "vsync", "max_fps"]},
              "pass_settings": [{k:p[k] for k in ["render_height", "render_size", "refresh_hz", "vsync", "max_fps", "quality", "elapsed_s"]} for p in batches],
              "scenes": {}}
    for scene in sorted(expected):
        metrics = [{k:v["median"] for k,v in p["segments"][scene]["summary"].items()} for p in batches]
        baseline = (metrics[0]["gpu_ms"] + metrics[2]["gpu_ms"]) / 2
        assert baseline > 0 and metrics[0]["gpu_ms"] > 0
        reduction = (1 - metrics[1]["gpu_ms"] / baseline) * 100
        drift = (metrics[2]["gpu_ms"] / metrics[0]["gpu_ms"] - 1) * 100
        result["scenes"][scene] = {"medians": metrics, "gpu_reduction_540_percent": reduction, "gpu_drift_720_percent": drift}
        cells = [f"{m['frame_ms']:.2f} / {m['gpu_ms']:.2f}" for m in metrics]
        rows.append(f"| {scene} | " + " | ".join(cells) + f" | {reduction:.1f}% | {drift:+.1f}% |")
    temperatures = json.loads((OUT / "temperatures.json").read_text())
    result["temperatures"] = {"min_c": min(t["temperature_c"] for t in temperatures if t["temperature_c"] is not None),
                              "max_c": max(t["temperature_c"] for t in temperatures if t["temperature_c"] is not None),
                              "largest_gap_s": max((b["elapsed_s"]-a["elapsed_s"] for a,b in zip(temperatures,temperatures[1:])), default=0)}
    assert (OUT / "player-package-before.txt").read_bytes() == (OUT / "player-package-after.txt").read_bytes()
    (OUT / "validated-sweep.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    (OUT / "comparison.md").write_text("\n".join(rows) + "\n", encoding="utf-8")
    print("\n".join(rows))


if __name__ == "__main__":
    main()
